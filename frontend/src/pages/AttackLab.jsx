function drawBox(ctx, x, y, w, h, bg, stroke, r = 6) {
  ctx.beginPath()
  ctx.roundRect(x, y, w, h, r)
  ctx.fillStyle = bg
  ctx.fill()
  ctx.strokeStyle = stroke
  ctx.lineWidth = 1
  ctx.stroke()
}

function drawLabel(ctx, text, x, y, color = '#d7e2dc', size = 11, align = 'center') {
  ctx.fillStyle = color
  ctx.font = `${size}px monospace`
  ctx.textAlign = align
  ctx.fillText(text, x, y)
}

function arrowH(ctx, x1, y, x2, color = '#8aa1a8') {
  ctx.strokeStyle = color
  ctx.lineWidth = 1.5
  ctx.beginPath()
  ctx.moveTo(x1, y)
  ctx.lineTo(x2, y)
  ctx.stroke()
  ctx.beginPath()
  ctx.moveTo(x2 - 6, y - 4)
  ctx.lineTo(x2, y)
  ctx.lineTo(x2 - 6, y + 4)
  ctx.stroke()
}

