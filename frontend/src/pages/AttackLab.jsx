export default function AttackLab() {
  const [selected, setSelected] = useState(ATTACKS[0].id)
  const [rollNo, setRollNo] = useState('')
  const [pin, setPin] = useState('')
  const [allowLiveProbe, setAllowLiveProbe] = useState(false)
  const [terminal, setTerminal] = useState([
    '$ boot attacker console',
    '$ load secure-vote profile',
    '$ awaiting scenario...',
  ])
  const [audit, setAudit] = useState([
    { time: nowStr(), level: 'INFO', text: 'Attack Lab initialized in educational mode.' },
    { time: nowStr(), level: 'INFO', text: 'No production exploit code will be executed.' },
  ])
  const [dbState, setDbState] = useState({ nullifier: 'b3f4d10a...', is_decoy: '0', status: 'live', leaf: 'a3f9...', votes: 3 })
  const [result, setResult] = useState(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')
  const [activeTab, setActiveTab] = useState('flow')

  const canvasRef = useRef(null)
  const animCleanupRef = useRef(null)

  const attack = useMemo(() => ATTACKS.find(a => a.id === selected), [selected])

  const stopAnim = useCallback(() => {
    if (animCleanupRef.current) { animCleanupRef.current(); animCleanupRef.current = null }
  }, [])

  const startAnim = useCallback(() => {
    stopAnim()
    const canvas = canvasRef.current
    if (!canvas) return
    const ctx = canvas.getContext('2d')
    const fn = ANIM_MAP[attack.animType]
    if (fn) animCleanupRef.current = fn(ctx)
  }, [attack, stopAnim])

  // Reset on attack change
  useEffect(() => {
    setResult(null); setError(''); setActiveTab('flow')
    stopAnim()
    const canvas = canvasRef.current
    if (canvas) { const ctx = canvas.getContext('2d'); ctx.clearRect(0, 0, canvas.width, canvas.height) }
  }, [selected, stopAnim])

  useEffect(() => () => stopAnim(), [stopAnim])

  function addAudit(level, text) {
    setAudit(prev => [{ time: nowStr(), level, text }, ...prev].slice(0, 12))
  }
  function addTerminal(line) {
    setTerminal(prev => [...prev, line])
  }

  async function runAttack() {
    setLoading(true); setError(''); setResult(null)
    const lines = attack.commands.map(c => `$ ${c}`)
    setTerminal([...lines, '$ stream defense telemetry'])
    addAudit('WARN', `${attack.title} simulation started.`)
    startAnim()

    try {
      let data
      if (attack.backend) {
        const resp = await fetch(`${API_BASE}/attack/run`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            scenario_id: attack.backend,
            roll_no: rollNo || null,
            pin: pin || null,
            allow_live_probe: allowLiveProbe,
          }),
        })
        if (!resp.ok) { const e = await resp.json(); throw new Error(e.detail || resp.statusText) }
        data = await resp.json()
      } else {
        // Frontend-only simulation (dom_hijack, db_tamper have no backend route)
        data = {
          verdict: attack.status === 'defended' ? 'defended' : attack.status,
          summary: attack.defense,
          events: [
            { status: 'attack', title: 'Payload staged', detail: attack.short },
            { status: attack.status === 'defended' ? 'blocked' : 'observed', title: 'System response', detail: attack.defense },
            { status: attack.status === 'defended' ? 'defended' : 'failed', title: 'Residual risk', detail: attack.limitation },
          ],
        }
      }

      setResult(data)

      // DB side-effects
      if (attack.id === 'double_vote') setDbState(s => ({ ...s, nullifier: 'COLLISION BLOCKED', status: 'constraint' }))
      if (attack.id === 'panic_pin') setDbState(s => ({ ...s, is_decoy: '1 (decoy)', status: 'skipped' }))
      if (attack.id === 'db_tamper') setDbState(s => ({ ...s, leaf: 'HASH MISMATCH', status: 'TAMPER' }))

      addTerminal(`> verdict=${data.verdict}`)
      addTerminal(`> summary="${data.summary.slice(0, 60)}..."`)
      addTerminal('> simulation complete')
      addAudit(data.verdict === 'defended' ? 'PASS' : 'RISK', data.summary.slice(0, 60))
    } catch (err) {
      const msg = err.message || 'Unknown error'
      setError(msg)
      addTerminal(`! ${msg}`)
      addAudit('ERR', msg)
    }
    setLoading(false)
  }

  return (
    <div style={{ minHeight: '100vh', background: '#070a0d', color: '#d7e2dc', padding: 20, fontFamily: 'monospace' }}>
      {/* Title bar */}
      <div style={{ display: 'flex', alignItems: 'center', gap: 10, marginBottom: 16, border: '1px solid #26343a', padding: '10px 14px', borderRadius: 6, background: '#10161a' }}>
        <span style={{ width: 10, height: 10, borderRadius: '50%', background: '#e24b4a', display: 'inline-block' }} />
        <span style={{ width: 10, height: 10, borderRadius: '50%', background: '#ef9f27', display: 'inline-block' }} />
        <span style={{ width: 10, height: 10, borderRadius: '50%', background: '#639922', display: 'inline-block' }} />
        <span style={{ flex: 1, textAlign: 'center', color: '#8aa1a8', fontSize: 11 }}>secure-vote — attacker dashboard</span>
        <span style={{ color: '#ffb3b3', border: '1px solid #8a1a1a', padding: '3px 8px', borderRadius: 4, fontSize: 10 }}>EDUCATIONAL SANDBOX</span>
      </div>

      {/* 3-col grid */}
      <div style={{ display: 'grid', gridTemplateColumns: '250px 1.1fr 0.9fr', gap: 14, alignItems: 'start' }}>
        {/* LEFT: Attack list */}
        <div>
          <div style={{ color: '#8aa1a8', fontSize: 10, letterSpacing: 2, marginBottom: 10 }}>ATTACK VECTORS</div>
          {ATTACKS.map(a => (
            <AttackButton key={a.id} attack={a} selected={selected} onSelect={id => { setSelected(id) }} />
          ))}
        </div>

        {/* MIDDLE */}
        <div>
          <Panel title="LIVE TERMINAL">
            <div style={{ padding: 14 }}>
              <div style={{ color: '#ffb3b3', fontSize: 11, marginBottom: 4 }}>target: {attack.target}</div>
              <div style={{ fontSize: 20, fontWeight: 700, fontFamily: 'Georgia, serif', marginBottom: 6 }}>{attack.title}</div>
              <div style={{ color: '#8aa1a8', fontSize: 12, lineHeight: 1.5, marginBottom: 12 }}>{attack.short}</div>

              {attack.hasInputs && (
                <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 8, marginBottom: 10 }}>
                  <input value={rollNo} onChange={e => setRollNo(e.target.value)} placeholder="roll number" autoComplete="off"
                    style={{ background: '#070a0d', color: '#d7e2dc', border: '1px solid #26343a', borderRadius: 4, padding: 8, fontFamily: 'monospace', fontSize: 11 }} />
                  <input value={pin} onChange={e => setPin(e.target.value.replace(/\D/g, '').slice(0, 12))} placeholder="leaked PIN" type="password" inputMode="numeric" autoComplete="off"
                    style={{ background: '#070a0d', color: '#d7e2dc', border: '1px solid #26343a', borderRadius: 4, padding: 8, fontFamily: 'monospace', fontSize: 11 }} />
                </div>
              )}

              {attack.id === 'double_vote' && (
                <label style={{ display: 'flex', alignItems: 'center', gap: 8, color: '#8aa1a8', fontSize: 11, marginBottom: 10 }}>
                  <input type="checkbox" checked={allowLiveProbe} onChange={e => setAllowLiveProbe(e.target.checked)} />
                  allow live duplicate insert probe
                </label>
              )}

              {/* Animation canvas */}
              <div style={{ position: 'relative', width: '100%', height: 180, marginBottom: 12, borderRadius: 4, overflow: 'hidden', background: '#070a0d', border: '1px solid #1b252a' }}>
                <canvas ref={canvasRef} width={480} height={180} style={{ width: '100%', height: '100%' }} />
                {!loading && !result && (
                  <div style={{ position: 'absolute', inset: 0, display: 'flex', alignItems: 'center', justifyContent: 'center', color: '#26343a', fontSize: 11, pointerEvents: 'none' }}>
                    → run simulation to start animation
                  </div>
                )}
              </div>

              <button
                onClick={runAttack}
                disabled={loading}
                style={{ width: '100%', border: 'none', borderRadius: 6, background: loading ? '#4a1010' : '#8a1a1a', color: 'white', padding: 13, letterSpacing: 2, fontFamily: 'monospace', fontSize: 12, cursor: loading ? 'default' : 'pointer', transition: 'background .2s' }}
              >
                {loading ? 'RUNNING ATTACK...' : 'EXECUTE SIMULATION'}
              </button>
              {error && <div style={{ color: '#ff6b6b', marginTop: 10, fontSize: 11 }}>{error}</div>}
            </div>
          </Panel>

          <Panel title="DUMMY SHELL">
            <TerminalView lines={terminal} />
          </Panel>
        </div>

        {/* RIGHT */}
        <div>
          <Panel title="DUMMY LIVE DATABASE">
            <DbView dbState={dbState} />
          </Panel>
          <Panel title="DUMMY AUDIT LOG">
            <AuditLog entries={audit} />
          </Panel>
        </div>
      </div>

      {/* Bottom tab panel */}
      <TabPanel attack={attack} result={result} activeTab={activeTab} onTabChange={setActiveTab} />
    </div>
  )
}